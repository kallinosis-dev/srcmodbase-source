bool CVPC::AreSolutionDepenenciesActual(CUtlPathStringHolder dependenciesPath,
                                        const CUtlVector<CDependency_Project*>& referencedProjects)
{
	if (!Sys_Exists(dependenciesPath))
		return false;

	CUtlBuffer dependsFileTemp;

	if (!Sys_LoadFileIntoBuffer(dependenciesPath, dependsFileTemp, true))
	{
		logging::Warning("Error reading dependencies file %s", dependenciesPath.Get());
		return false;
	}

	CUtlInplaceBuffer dependsFile(0, 0, CUtlBuffer::TEXT_BUFFER);
	if (!dependsFileTemp.ConvertCRLF(dependsFile))
		dependsFile.SwapCopy(dependsFileTemp);

	CUtlDict<bool> dependeciesDict{k_eDictCompareTypeCaseSensitive, referencedProjects.Count()};


	for (auto refproj : referencedProjects)
		dependeciesDict.Insert(refproj->GetProjectFileName(), false);


	char* rawLine;
	int rawLineLen;
	char lineBuffer[512];


	while (dependsFile.InplaceGetLinePtr(&rawLine, &rawLineLen))
	{
		V_strncpy(lineBuffer, rawLine, rawLineLen);


		auto i = dependeciesDict.Find(lineBuffer);

		if (!dependeciesDict.IsValidIndex(i)) // This project is not present in current run, but did in previous
			return false;

		dependeciesDict.Element(i) = true;
	}

	for (uint i = 0; i < dependeciesDict.Count(); ++i)
		if (dependeciesDict.IsValidIndex(i))
			if (dependeciesDict.Element(i) == false) // This project is present in current run, but not in previous
				return false;

	return true;
}

void CVPC::WriteSolutionDependencies(CUtlPathStringHolder dependenciesPath,
                                     const CUtlVector<CDependency_Project*>& referencedProjects)
{
	FILE* file;
	if (fopen_s(&file, dependenciesPath, "wt") != 0)
	{
		logging::Warning("Error opening solution dependencies file (%s) for write", dependenciesPath.Get());
		return;
	}

	for (auto refproj : referencedProjects)
		fprintf_s(file, "%s\n", refproj->GetProjectFileName());

	fclose(file);
}

//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
void CVPC::HandleMKSLN(IBaseSolutionGenerator* pSolutionGenerator,
                       IBaseSolutionGenerator* pSolutionGenerator2,
                       CProjectDependencyGraph& dependencyGraph)
{
	if (!VPC_AreProjectDependenciesSupportedForThisTargetPlatform())
		logging::Error("MKSLN not supported for %s yet!", conditionals.GetTargetPlatformName());

	if (!pSolutionGenerator)
		logging::Error("No solution generator exists for this platform.");

	// can be called on behalf of /mksln (and thus have dependencies) or /p4sln (and need to create them based on CL #)
	if (!dependencyGraph.HasGeneratedDependencies())
	{
		// mksln is based on just the CL specified projects
		dependencyGraph.BuildProjectDependencies(0);
	}

	// GenerateBuildSet basically generates what we want, except it uses projectIndex_t's, meaning that
	// we don't know what subset of games we should use until we've called VPC_IterateTargetProjects.
	CUtlVector<CDependency_Project*> referencedProjects;
	dependencyGraph.TranslateProjectIndicesToDependencyProjects(m_TargetProjects, referencedProjects);

	// Generate a solution file.
	CUtlPathStringHolder fullSolutionPath;
	if (V_IsAbsolutePath(m_MKSolutionFilename.Get()))
	{
		fullSolutionPath.Set(m_MKSolutionFilename.Get());
	}
	else
	{
		fullSolutionPath.ComposeFileName(g_pVPC->GetStartDirectory(), m_MKSolutionFilename.Get());
	}

	//strip off any specified extension and let the generators append their own
	fullSolutionPath.StripExtension();

	CUtlPathStringHolder dependenciesPath = fullSolutionPath;
	dependenciesPath.Append(".vpc_deps");

	if (!m_bForceGenerate && AreSolutionDepenenciesActual(dependenciesPath, referencedProjects))
	{
		logging::Status(true, "Keeping current solution.");
		return;
	}
	
	pSolutionGenerator->GenerateSolutionFile(fullSolutionPath, referencedProjects);

	if (pSolutionGenerator2)
	{
		pSolutionGenerator2->GenerateSolutionFile(fullSolutionPath, referencedProjects);
	}

	logging::Status(true, "Updating solution dependencies file...");
	WriteSolutionDependencies(dependenciesPath, referencedProjects);
}

//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
void CVPC::DetermineSolutionGenerator()
{
	extern IBaseSolutionGenerator*GetSolutionGenerator_Win32();
	extern IBaseSolutionGenerator*GetMakefileSolutionGenerator();

	bool bIsLinuxPlatform = conditionals.IsDefined("LINUXALL");
	bool bIsAndroidPlatform = conditionals.IsDefined("ANDROIDALL");

	// Under Windows we have the ability to generate makefiles so if they specified a linux config,
	// or if they're building the (non-SRCDS) dedicated server, then use the makefile generator
	bool bUseMakefile = bIsLinuxPlatform || bIsAndroidPlatform || conditionals.IsDefined("DEDICATED");


	if (bUseMakefile)
	{
		logging::StatusWithColor(true, Color(0, 255, 255, 255), "Using Makefile generator.");

		m_pSolutionGenerator = GetMakefileSolutionGenerator();

		if (conditionals.IsDefined("GENERATE_MAKEFILE_VCXPROJ"))
		{
			const char* pVSName = "2010";
			if (m_bUse2022)
				pVSName = "2022";
			else if (m_bUse2015)
				pVSName = "2015";
			else if (m_bUse2013)
				pVSName = "2013";
			else if (m_bUse2012)
				pVSName = "2012";

			logging::StatusWithColor(true, Color(0, 255, 255, 255), "Generating Makefile for Visual Studio %s", pVSName);
			m_pSolutionGenerator2 = GetSolutionGenerator_Win32();
		}
	}
	else
	{
		{
			if (m_bUse2022)
			{
				logging::StatusWithColor(true, Color(0, 255, 255, 255), "Generating for Visual Studio 2022.");
			}
			else if (m_bUse2015)
			{
				logging::StatusWithColor(true, Color(0, 255, 255, 255), "Generating for Visual Studio 2015.");
			}
			else if (m_bUse2013)
			{
				logging::StatusWithColor(true, Color(0, 255, 255, 255), "Generating for Visual Studio 2013.");
			}
			else if (m_bUse2012)
			{
				logging::StatusWithColor(true, Color(0, 255, 255, 255), "Generating for Visual Studio 2012.");
			}
			else
			{
				logging::StatusWithColor(true, Color(0, 255, 255, 255), "Generating for Visual Studio 2010.");
			}
			m_pSolutionGenerator = GetSolutionGenerator_Win32();
		}

		logging::Status(true, "\n");
	}
}

extern IBaseProjectGenerator* GetWin32ProjectGenerator_2010();
extern IBaseProjectGenerator* GetMakefileProjectGenerator();
extern IBaseProjectGenerator* GetAndroidProjectGenerator();
extern IVCProjWriter* GetWin32ProjectGenerator_VCProjWriter_2010();

void CVPC::DetermineProjectGenerator(CScript* projScript)
{
	if (m_pProjectGenerator)
		return; //already picked one for this project!


	bool bIsLinuxPlatform = conditionals.IsDefined("LINUXALL");
	bool bIsAndroidPlatform = conditionals.IsDefined("ANDROIDALL");
	bool bIsAndroidProject = conditionals.IsDefined("ANDROIDPROJECT");
	//android-specific project template, not just a dll/exe/lib compiled for android platform

	// Under Windows we have the ability to generate makefiles so if they specified a linux config,
	// or if they're building the (non-SRCDS) dedicated server, then use the makefile generator
	bool bUseAndroid = bIsAndroidProject && bIsAndroidPlatform;
	bool bUseMakefile = (bIsLinuxPlatform || bIsAndroidPlatform
		/* || IsConditionalDefined( "DEDICATED" )*/) && !bUseAndroid;

	if (bUseMakefile)
	{
		m_pProjectGenerator = GetMakefileProjectGenerator();

		// We partially support per-file compile settings in
		// makefiles but many things don't work (everything
		// except defines and includes) so disallow it.

		//TODO: Allow per-file compiler config on makefiles. Is this the right decision?
		m_bPerFileCompileConfig = true;

		// We do not support lib-within-lib for makefiles.
		m_bAllowLibWithinLib = false;
	}
	else if (bUseAndroid)
	{
		m_pProjectGenerator = GetAndroidProjectGenerator();
		// We do not support any kind of per-file
		// compile options because we leverage ANT to build android projects.
		m_bPerFileCompileConfig = false;
		// I don't even know what lib within a lib would look like for android yet, assuming it's just as bad as a generic binary
		m_bAllowLibWithinLib = false;
	}
	else
	{
		// MSVC does support lib-within-lib but we want to
		// direct people towards the cross-platform $LibDependsOn
		// feature so disallow lib containment.
		m_bAllowLibWithinLib = false;
		m_pProjectGenerator = GetWin32ProjectGenerator_2010();
	}

	m_pProjectGenerator->StartProject(projScript);
	if (m_pDependencyProject)
	{
		m_pDependencyProject->m_pProjectGenerator = m_pProjectGenerator;
	}
}

